#!/usr/bin/env python3
"""Bundle AETHER ModuleScripts into one portable Roblox Luau LocalScript.

This tool works offline and uses no remote code execution.
It does not grant code execution in third-party Roblox experiences.
"""
from __future__ import annotations

import argparse
import hashlib
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MODULES = ROOT / "src" / "shared"
CLIENT = ROOT / "src" / "client" / "Aether.client.luau"
OUTPUT = ROOT / "dist" / "AETHER.client.luau"

REQUIRE_PATTERN = re.compile(
    r'\brequire\s*\(\s*script\s*\.\s*Parent\s*\.\s*([A-Za-z_]\w*)\s*\)'
)
CLIENT_BOOTSTRAP = re.compile(
    r'local ReplicatedStorage = game:GetService\("ReplicatedStorage"\)\s*'
    r'local player = Players\.LocalPlayer\s*'
    r'local modules = ReplicatedStorage:WaitForChild\("Aether", 30\)\s*'
    r'assert\(modules, "AETHER: ReplicatedStorage\.Aether is missing; sync the Rojo project"\)\s*'
    r'local function module\(name\)\s*'
    r'return require\(modules:WaitForChild\(name, 15\)\)\s*'
    r'end',
    re.MULTILINE,
)

RUNTIME = """-- Generated by tools/build.py. Do not edit; edit src/shared or src/client.
-- Bundled for authorized LocalScript use in Roblox Studio.
-- No HTTP, loadstring, executor, or exploit dependencies.
local __aether_factories = {}
local __aether_cache = {}
local __aether_loading = {}
local function __aether_require(name)
    local cached = __aether_cache[name]
    if cached ~= nil then return cached end
    local factory = __aether_factories[name]
    assert(factory, "AETHER: missing bundled module: " .. tostring(name))
    assert(not __aether_loading[name], "AETHER: circular dependency: " .. name)
    __aether_loading[name] = true
    local ok, value = pcall(factory)
    __aether_loading[name] = nil
    if not ok then error("AETHER module " .. name .. ": " .. tostring(value), 2) end
    assert(value ~= nil, "AETHER: module returned nil: " .. name)
    __aether_cache[name] = value
    return value
end
"""

def build() -> str:
    paths = sorted(MODULES.glob("*.luau"))
    if not paths:
        raise RuntimeError("No Luau modules found")
    names = {p.stem for p in paths}
    sections = [RUNTIME]

    for p in paths:
        source = p.read_text(encoding="utf-8").lstrip("\ufeff")
        refs = set(REQUIRE_PATTERN.findall(source))
        unknown = refs - names
        if unknown:
            raise RuntimeError(f"{p.name}: missing modules: {sorted(unknown)}")
        replaced = REQUIRE_PATTERN.sub(
            lambda m: f'__aether_require("{m.group(1)}")', source
        )
        if "require(script.Parent" in replaced:
            raise RuntimeError(f"{p.name}: unsupported require path")
        sections.append(
            f'\n-- BEGIN MODULE {p.stem}\n'
            f'__aether_factories["{p.stem}"] = function()\n'
            f'{replaced}\n'
            'end\n'
            f'-- END MODULE {p.stem}\n'
        )

    client = CLIENT.read_text(encoding="utf-8").lstrip("\ufeff")
    client, count = CLIENT_BOOTSTRAP.subn(
        'local player = Players.LocalPlayer\n'
        'local function module(name)\n'
        '    return __aether_require(name)\n'
        'end', client
    )
    if count != 1:
        raise RuntimeError(
            f"Client bootstrap pattern changed (matches={count}); "
            "update bundler before publishing."
        )
    if "modules:WaitForChild" in client or "ReplicatedStorage:WaitForChild" in client:
        raise RuntimeError("Unexpected external module reference in client")
    sections.append("\n-- BEGIN CLIENT\n" + client + "\n-- END CLIENT\n")
    return "\n".join(sections)

def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if dist is not current")
    args = parser.parse_args()
    result = build()
    sha = hashlib.sha256(result.encode("utf-8")).hexdigest()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != result:
            raise SystemExit("Bundle is out of date. Run python tools/build.py")
        print(f"OK: {OUTPUT.relative_to(ROOT)} sha256={sha[:16]}")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(result, encoding="utf-8")
        print(f"Built {OUTPUT.relative_to(ROOT)} ({len(result.encode('utf-8'))} bytes); sha256={sha[:16]}")

if __name__ == "__main__":
    main()